(* {1 Dispatch} *)

let err_unknown_format s =
  Fmt.kstr
    (fun msg -> Error msg)
    "unknown format %S (expected: text, md, html)" s

let format_of_string = function
  | "text" -> Ok Text
  | "md" | "markdown" -> Ok Markdown
  | "html" -> Ok Html
  | s -> err_unknown_format s

let render_rule ~format rule =
  match format with
  | Text -> Text.render_rule rule
  | Markdown -> Markdown.render_rule rule
  | Html -> Html.render_rule rule

let render_all ~format rules =
  match format with
  | Text -> Text.render_all rules
  | Markdown -> Markdown.render_all rules
  | Html -> Html.render_all rules

let render_index = Text.render_index
