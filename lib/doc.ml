(** Render rule documentation in the format the user asks for. *)

type format = Text | Markdown | Html

let category_of_code code =
  let n = int_of_string (String.sub code 1 (String.length code - 1)) in
  if n < 100 then "Complexity"
  else if n < 200 then "Security/Safety"
  else if n < 300 then "Style/Modernization"
  else if n < 400 then "Naming Conventions"
  else if n < 500 then "Documentation"
  else if n < 600 then "Project Structure"
  else "Testing"

let categories =
  [
    ("Complexity", "E001-E099", "Code complexity and maintainability issues");
    ( "Security/Safety",
      "E100-E199",
      "Potential security vulnerabilities and unsafe code patterns" );
    ( "Style/Modernization",
      "E200-E299",
      "Code style and modernization recommendations" );
    ( "Naming Conventions",
      "E300-E399",
      "Identifier naming convention violations" );
    ("Documentation", "E400-E499", "Missing or incorrect documentation");
    ( "Project Structure",
      "E500-E599",
      "Project organization and configuration issues" );
    ("Testing", "E600-E699", "Test coverage and test quality issues");
  ]

(* {1 Text — plain terminal output} *)

module Text = struct
  let example (ex : Rule.example) =
    let label = if ex.is_good then "Good:" else "Bad:" in
    Fmt.str "  %s\n%s\n" label
      (String.split_on_char '\n' ex.code
      |> List.map (fun l -> "    " ^ l)
      |> String.concat "\n")

  let render_rule rule =
    let buf = Buffer.create 256 in
    let ppf = Fmt.with_buffer buf in
    Fmt.pf ppf "[%s] %s\n" (Rule.code rule) (Rule.title rule);
    Fmt.pf ppf "  Category: %s\n" (category_of_code (Rule.code rule));
    Fmt.pf ppf "\n%s\n" (Rule.hint rule);
    (match Rule.examples rule with
    | [] -> ()
    | exs ->
        Buffer.add_string buf "\nExamples:\n";
        List.iter (fun ex -> Buffer.add_string buf (example ex)) exs);
    Buffer.contents buf

  let render_all rules =
    rules |> List.map render_rule
    |> String.concat "\n----------------------------------------\n\n"

  (** One-line-per-rule index: [Ecode  title  (category)]. Grep-friendly: pipe
      through [grep magic] or [grep Naming] to find what you're after. *)
  let render_index rules =
    let max_code =
      List.fold_left
        (fun acc r -> max acc (String.length (Rule.code r)))
        0 rules
    in
    let max_title =
      List.fold_left
        (fun acc r -> max acc (String.length (Rule.title r)))
        0 rules
    in
    rules
    |> List.map (fun r ->
        Fmt.str "%-*s  %-*s  (%s)" max_code (Rule.code r) max_title
          (Rule.title r)
          (category_of_code (Rule.code r)))
    |> String.concat "\n"
end

(* {1 Markdown — style guide} *)

module Markdown = struct
  let example (ex : Rule.example) =
    let label = if ex.is_good then "**Good:**" else "**Bad:**" in
    Fmt.str "%s\n```ocaml\n%s\n```\n" label ex.code

  let examples = function
    | [] -> ""
    | exs ->
        "\n\n**Examples:**\n\n" ^ (List.map example exs |> String.concat "\n")

  let render_rule rule =
    Fmt.str "### [%s] %s\n\n%s%s\n" (Rule.code rule) (Rule.title rule)
      (Rule.hint rule)
      (examples (Rule.examples rule))

  let render_rule_by_code rule_code =
    match List.find_opt (fun r -> Rule.code r = rule_code) Data.all_rules with
    | None -> Fmt.str "### [%s] Rule not found\n\n" rule_code
    | Some r -> render_rule r

  let rec of_guide_element = function
    | Guide.Title s -> Fmt.str "# %s\n" s
    | Section (title, elements) ->
        let content =
          List.map of_guide_element elements |> String.concat "\n"
        in
        Fmt.str "## %s\n\n%s" title content
    | Paragraph s -> Fmt.str "%s\n" s
    | Code s -> Fmt.str "```ocaml\n%s\n```\n" s
    | Rule rule_code -> render_rule_by_code rule_code

  let style_guide () =
    let header =
      "<!-- This file is auto-generated by `merlint help --format=md --all`. -->\n\
       <!-- Do not edit manually. Edit lib/guide.ml instead. -->\n\n"
    in
    let content =
      List.map of_guide_element Guide.content |> String.concat "\n"
    in
    header ^ content

  let render_all _rules = style_guide ()
end

