  let add_pattern pattern class_name escaped segments =
    let re = Re.Perl.compile_pat pattern in
    Re.all re escaped
    |> List.iter (fun g ->
        let start = Re.Group.start g 0 in
        let stop = Re.Group.stop g 0 in
        let text = Re.Group.get g 0 in
        segments := (start, stop, class_name, text) :: !segments)

  let add_keywords escaped segments =
    List.iter
      (fun kw ->
        let pattern = Fmt.kstr Re.Perl.compile_pat {|\b%s\b|} kw in
        Re.all pattern escaped
        |> List.iter (fun g ->
            let start = Re.Group.start g 0 in
            let stop = Re.Group.stop g 0 in
            segments := (start, stop, "kw", kw) :: !segments))
      ocaml_keywords

  let drop_overlaps segments =
    let sorted =
      List.sort (fun (s1, _, _, _) (s2, _, _, _) -> compare s1 s2) segments
    in
    let acc = ref [] in
    let last = ref (-1) in
    List.iter
      (fun (start, stop, c, t) ->
        if start >= !last then begin
          acc := (start, stop, c, t) :: !acc;
          last := stop
        end)
      sorted;
    List.rev !acc

  let span c t = Fmt.str {|<span class="%s">%s</span>|} c t

  let module_path text =
    match String.split_on_char '.' text with
    | [ m; f ] ->
        Fmt.str {|<span class="md">%s</span>.<span class="fn">%s</span>|} m f
    | _ -> text

  let render_segment c t = if c = "module_path" then module_path t else span c t

  let weave escaped segments =
    let buf = Buffer.create (String.length escaped + 32) in
    let last = ref 0 in
    List.iter
      (fun (start, stop, c, t) ->
        if start > !last then
          Buffer.add_substring buf escaped !last (start - !last);
        Buffer.add_string buf (render_segment c t);
        last := stop)
      segments;
    if !last < String.length escaped then
      Buffer.add_substring buf escaped !last (String.length escaped - !last);
    Buffer.contents buf

  let highlight code =
    let process line =
      let escaped = escape line in
      let segments = ref [] in
      add_pattern {|\(\*.*?\*\)|} "cm" escaped segments;
      add_pattern {|"(?:[^"\\]|\\.)*"|} "st" escaped segments;
      add_pattern {|\b[0-9]+\.?[0-9]*\b|} "nu" escaped segments;
      add_keywords escaped segments;
      add_pattern {|\b[A-Z][a-zA-Z0-9_']*\.[a-z][a-zA-Z0-9_']*\b|} "module_path"
        escaped segments;
      add_pattern {|\b[A-Z][a-zA-Z0-9_']*\b|} "cn" escaped segments;
      weave escaped (drop_overlaps !segments)
    in
    code |> String.split_on_char '\n' |> List.map process |> String.concat "\n"

